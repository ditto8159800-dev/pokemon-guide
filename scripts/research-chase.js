#!/usr/bin/env node
/* Collect each kept Japanese set's singles from TCGplayer's "Pokemon Japan" product line (market price, rarity, number),
 * merged with the SNKRDUNK set listing, into data/tcgplayer/<set>.json. Used as the market-price pool for the community-picked
 * chase cards (content/chase-evidence.json -> content/chase-picks.json via `node scripts/research-chase.js --pick`).
 * Usage: node scripts/research-chase.js [--set=M2] [--pick]   */
const fs=require('fs'),path=require('path');const ROOT=path.join(__dirname,'..');
const args=Object.fromEntries(process.argv.slice(2).map(a=>{const [k,v]=a.replace(/^--/,'').split('=');return [k,v??true];}));
const UA='Mozilla/5.0 (pokemon-guide price research)';const sleep=ms=>new Promise(r=>setTimeout(r,ms));const today=new Date().toISOString().slice(0,10);
async function tcgSearch(q,from=0){await sleep(700);
  try{const r=await fetch(`https://mp-search-api.tcgplayer.com/v1/search/request?q=${encodeURIComponent(q)}&isList=false`,{method:'POST',headers:{'User-Agent':UA,'Content-Type':'application/json'},
    body:JSON.stringify({algorithm:'sales_synonym_v2',from,size:24,filters:{term:{productLineName:['pokemon-japan'],productTypeName:['Cards']},range:{},match:{}},listingSearch:{context:{cart:{}},filters:{term:{sellerStatus:'Live',channelId:0},range:{quantity:{gte:1}},exclude:{channelExclusion:0}}},context:{cart:{},shippingCountry:'US',userProfile:{}},settings:{useFuzzySearch:false,didYouMean:{}},sort:{}})});
    if(!r.ok) return [];const d=await r.json();return d.results?.[0]?.results||[];}catch(e){return [];}}
const CFG=JSON.parse(fs.readFileSync(path.join(ROOT,'content/site-config.json'),'utf8'));
const sets=JSON.parse(fs.readFileSync(path.join(ROOT,'data/sets.json'),'utf8'));
const keep=Object.keys(CFG.keep.hot).filter(k=>!args.set||k==='ja:'+args.set);
(async()=>{
 if(args.pick){
  // pick: top 10 of the community ranking (content/chase-evidence.json "ranking", else Pokeca-Now flea-market medians), matched to
  // the exact TCGplayer Japanese product and SNKRDUNK product (same number, same variant) so prices and links point at that card.
  const EV=JSON.parse(fs.readFileSync(path.join(ROOT,'content/chase-evidence.json'),'utf8')).sets;const out={};
  const norm=n=>String(n).split('/')[0].replace(/^0+(?=\d)/,'');
  const isMirrorName=n=>/Pattern|Mirror|Master Ball|Poke Ball|Monster Ball/i.test(n);
  for(const key of keep){const id=key.split(':')[1];const ev=EV[key]||{};
   const pc=path.join(ROOT,'data/community',`pokecanow-${id}.json`);const PC=fs.existsSync(pc)?JSON.parse(fs.readFileSync(pc,'utf8')):null;
   let rs,ranking;
   if(ev.ranking){ranking=ev.ranking;rs=ev.rankingSource;}
   else if(PC){ranking=PC.cards.filter(c=>c.price>0);rs={name:'Pokeca-Now フリマ実売中央値（メルカリ・Y!フリマ・ヤフオク）',url:PC.url,date:PC.fetched,currency:'JPY'};}
   else {console.log(id,'no ranking source');continue;}
   ranking=[...ranking].sort((a,b)=>b.price-a.price).slice(0,10);
   const tf=path.join(ROOT,'data/tcgplayer',id+'.json');const TP=fs.existsSync(tf)?JSON.parse(fs.readFileSync(tf,'utf8')).cards:[];
   const sf=path.join(ROOT,'data/snkrdunk',id+'.json');const SK=fs.existsSync(sf)?JSON.parse(fs.readFileSync(sf,'utf8')).items:[];
   const cards=ranking.map((r,i)=>{const lid=/^\d/.test(r.num)?norm(r.num):r.num;const master=r.variant==='master'||/マスターボール/.test(r.rarity||'');
     let t=TP.filter(x=>(/^\d/.test(r.num)?norm(x.number)===lid:String(x.number)===r.num));
     t=master?t.filter(x=>/Master Ball/i.test(x.name)):t.filter(x=>!isMirrorName(x.name));
     t.sort((a,b)=>(b.marketPrice||0)-(a.marketPrice||0));
     let k=SK.filter(x=>x.num===lid.replace(/^0+/,''));
     k=master?k.filter(x=>/Master Ball Mirror/i.test(x.name)):k.filter(x=>!/Mirror/i.test(x.name));k=k.filter(x=>!/Error|Misprint|Campaign|Promo|^【/i.test(x.name));
     k.sort((a,b)=>(b.listingCount||0)-(a.listingCount||0)||(b.minPrice||0)-(a.minPrice||0));
     return {rank:i+1,name:r.name,rarity:r.rarity||null,num:r.num,localId:lid,variant:master?'master':null,marketJpy:r.price,psa10Jpy:r.psa10??null,
       tcgplayerId:t[0]?.productId||null,tcgplayerName:t[0]?.name||null,snkId:(ev.snkIds||{})[r.num]||k[0]?.id||null,snkName:k[0]?.name||null};});
   out[key]={rankingSource:rs,cards};
   console.log(id,cards.map(c=>`${c.name}${c.variant?'(MB)':''} ¥${c.marketJpy} tp:${c.tcgplayerId?'Y':'-'} snk:${c.snkId?'Y':'-'}`).join(' | '));
  }
  fs.writeFileSync(path.join(ROOT,'content/chase-picks.json'),JSON.stringify({_note:'Generated by scripts/research-chase.js --pick from content/chase-evidence.json + data/community + data/tcgplayer + data/snkrdunk. Do not edit by hand.',generated:today,sets:out},null,1));
  return;
 }

 if(!args.pick){
  for(const key of keep){const s=sets.find(x=>x.key===key)||{id:key.split(':')[1]};const code=s.id.toLowerCase();const seen=new Map();
   const qs=[s.id,`${s.id} SAR`,`${s.id} SR`,`${s.id} AR`,`${s.id} UR`,`${s.id} HR`,`${s.id} CHR`,`${s.id} CSR`,`${s.id} ex`,s.translated||s.enEquivText||''].filter(Boolean);
   for(const q of qs){for(let from=0;from<120;from+=24){const res=await tcgSearch(q,from);res.filter(x=>String(x.setName||'').toLowerCase().startsWith(code+':')).forEach(x=>seen.set(Math.round(x.productId),x));if(res.length<24)break;}}
   const cards=[...seen.values()].map(x=>({productId:Math.round(x.productId),name:String(x.productName).replace(/\s*-\s*[\w]+\/\d+.*$/,'').trim(),number:x.customAttributes?.number||'',rarity:x.rarityName||'',marketPrice:x.marketPrice||null,setName:x.setName}));
   if(cards.length) fs.writeFileSync(path.join(ROOT,'data/tcgplayer',s.id+'.json'),JSON.stringify({set:s.id,fetched:today,source:'TCGplayer',cards},null,1));
   console.log(s.id,'TCGplayer cards',cards.length,'priced',cards.filter(c=>c.marketPrice>0).length);
  }
 }
})();
